_REQUIRED_TOP_KEYS = frozenset(
    {"_metadata", "driver_scores", "scale_breaker", "pattern_readiness", "evaluator_coverage", "evaluator_results"}
)
_REQUIRED_METADATA_KEYS = frozenset({"engine_version", "timestamp", "manifest_version"})


class TestEndToEnd:
    """End-to-end tests calling run() with fixture data and the real manifest."""

    def test_run_produces_valid_summary(self, tmp_path: Path) -> None:
        """run() returns a dict matching the Schema 3 shape with all required keys."""
        collected = setup_frontier_collected(tmp_path)
        output_path = tmp_path / "frontier-summary.json"

        result = score_frontier.run(
            manifest_path=str(MANIFEST_PATH),
            collected_dir=str(collected),
            output_path=str(output_path),
        )

        for key in _REQUIRED_TOP_KEYS:
            assert key in result, f"Missing top-level key: {key}"

        for mk in _REQUIRED_METADATA_KEYS:
            assert mk in result["_metadata"], f"Missing _metadata key: {mk}"

        for driver_id in score_frontier.DRIVER_IDS:
            assert driver_id in result["driver_scores"], f"Missing driver: {driver_id}"
            ds = result["driver_scores"][driver_id]
            for field in ("score", "level_label", "questions_answered", "questions_total", "confidence"):
                assert field in ds, f"driver_scores[{driver_id}] missing {field}"

        sb = result["scale_breaker"]
        for field in ("driver", "score", "tied_with", "rationale"):
            assert field in sb, f"scale_breaker missing {field}"

        for pid in ("1", "2", "3", "4", "5", "6"):
            assert pid in result["pattern_readiness"], f"Missing pattern {pid}"
            pr = result["pattern_readiness"][pid]
            assert "ready" in pr and "gap_drivers" in pr and "min_gap" in pr

