class TestScoreDriver:
    """Unit tests for the score_driver() function."""

    @staticmethod
    def _yes_answers(questions: list[dict]) -> dict[str, dict]:
        return {q["question_id"]: {"value": "yes"} for q in questions}

    @staticmethod
    def _no_answers(questions: list[dict]) -> dict[str, dict]:
        return {q["question_id"]: {"value": "no"} for q in questions}

    def test_all_yes_produces_500(self) -> None:
        """All 5 questions answered yes → score 500, label 'Optimized', confidence high."""
        questions = _make_five_level_questions("ai_strategy")
        answers = self._yes_answers(questions)
        result = score_frontier.score_driver("ai_strategy", questions, answers)
        assert result["score"] == 500
        assert result["level_label"] == "Optimized"
        assert result["confidence"] == "high"
        assert result["questions_answered"] == 5

    def test_all_no_produces_low(self) -> None:
        """All 5 questions answered no → score 0, label 'Below Initial'."""
        questions = _make_five_level_questions("ai_strategy")
        answers = self._no_answers(questions)
        result = score_frontier.score_driver("ai_strategy", questions, answers)
        assert result["score"] == 0
        assert result["level_label"] == "Below Initial"
        assert result["confidence"] == "high"

    def test_partial_climbs_correctly(self) -> None:
        """L100=yes, L200=yes, L300=partial (ratio 0.5 < 0.7) → score 250, label 'Repeatable+'."""
        questions = _make_five_level_questions("ai_strategy")
        answers = {
            "TST_100": {"value": "yes"},
            "TST_200": {"value": "yes"},
            "TST_300": {"value": "partial"},
            # TST_400 and TST_500 intentionally absent
        }
        result = score_frontier.score_driver("ai_strategy", questions, answers)
        assert result["score"] == 250
        assert result["level_label"] == "Repeatable+"
        assert result["level_breakdown"]["300"]["ratio"] == pytest.approx(0.5)
        assert result["level_breakdown"]["100"]["ratio"] == pytest.approx(1.0)
        assert result["level_breakdown"]["200"]["ratio"] == pytest.approx(1.0)

    def test_missing_answers_lower_confidence(self) -> None:
        """3 of 5 questions unanswered → questions_answered=2, confidence 'low'."""
        questions = _make_five_level_questions("ai_strategy")
        # Only L400 and L500 answered; L100, L200, L300 absent
        answers = {
            "TST_400": {"value": "yes"},
            "TST_500": {"value": "yes"},
        }
        result = score_frontier.score_driver("ai_strategy", questions, answers)
        assert result["questions_answered"] == 2
        assert result["confidence"] == "low"

    def test_skip_threshold_blocks_advancement(self) -> None:
        """L100=partial (ratio 0.5 < 0.7) → highest_fully_achieved=0, score=50, label 'Below Initial'."""
        questions = _make_five_level_questions("ai_strategy")
        answers = {"TST_100": {"value": "partial"}}
        result = score_frontier.score_driver("ai_strategy", questions, answers)
        assert result["score"] == 50
        assert result["level_label"] == "Below Initial"
        assert result["level_breakdown"]["100"]["ratio"] == pytest.approx(0.5)

    def test_scale_1_5_format_normalizes(self) -> None:
        """scale_1_5 answer value=3 → normalized 0.5; below threshold → score 50."""
        question = _make_question("Q_SCALE", "ai_strategy", 100, answer_format="scale_1_5")
        result = score_frontier.score_driver("ai_strategy", [question], {"Q_SCALE": {"value": 3}})
        # (3-1)/4 = 0.5 < 0.7 → score = int(round(0.5*100)) = 50
        assert result["score"] == 50
        assert result["level_label"] == "Below Initial"
        assert result["level_breakdown"]["100"]["ratio"] == pytest.approx(0.5)

    def test_text_format_excluded_from_scoring(self) -> None:
        """text format answers are not auto-scored → questions_answered=0, score=0."""
        question = _make_question("Q_TEXT", "ai_strategy", 100, answer_format="text")
        result = score_frontier.score_driver(
            "ai_strategy", [question], {"Q_TEXT": {"value": "Some descriptive text"}}
        )
        assert result["questions_answered"] == 0
        assert result["score"] == 0

    def test_multiple_questions_per_level_weighted_average(self) -> None:
        """Two L100 questions (weight 1.0): one yes, one no → ratio 0.5 → score 50."""
        questions = [
            _make_question("Q_A", "ai_strategy", 100, 1.0),
            _make_question("Q_B", "ai_strategy", 100, 1.0),
        ]
        answers = {"Q_A": {"value": "yes"}, "Q_B": {"value": "no"}}
        result = score_frontier.score_driver("ai_strategy", questions, answers)
        assert result["level_breakdown"]["100"]["ratio"] == pytest.approx(0.5)
        assert result["score"] == 50
        assert result["level_label"] == "Below Initial"

    def test_level_breakdown_keys_always_present(self) -> None:
        """level_breakdown always has keys '100' through '500' regardless of answers."""
        questions = _make_five_level_questions("business_strategy")
        result = score_frontier.score_driver("business_strategy", questions, {})
        for level in ("100", "200", "300", "400", "500"):
            assert level in result["level_breakdown"]
            lb = result["level_breakdown"][level]
            assert "answered" in lb and "total" in lb and "ratio" in lb

    def test_no_questions_for_driver_returns_zero(self) -> None:
        """Driver with no questions in manifest → score 0, confidence 'low'."""
        result = score_frontier.score_driver("ai_strategy", [], {})
        assert result["score"] == 0
        assert result["questions_total"] == 0
        assert result["questions_answered"] == 0


