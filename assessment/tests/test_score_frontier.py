def load_fixture(name: str) -> dict:
    """Load a JSON fixture file by name from the fixtures directory."""
    path = FIXTURES_DIR / name
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def write_json(path: Path, data: dict) -> None:
    """Write *data* as indented JSON to *path*, creating parent dirs."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)


def setup_frontier_collected(
    tmp_path: Path,
    fixture_name: str = "frontier_answers_partial.json",
) -> Path:
    """Copy a frontier answers fixture into a temp collected/ dir for run()."""
    collected = tmp_path / "collected"
    collected.mkdir()
    data = load_fixture(fixture_name)
    write_json(collected / "frontier.json", data)
    return collected


def _make_question(
    question_id: str,
    driver: str,
    level: int,
    weight: float = 1.0,
    answer_format: str = "yes_no_partial",
) -> dict:
    """Build a minimal question dict for unit tests."""
    return {
        "question_id": question_id,
        "driver": driver,
        "level": level,
        "scoring_weight": weight,
        "answer_format": answer_format,
        "auto_evaluable": False,
        "collection_methods": ["Manual"],
    }


def _make_five_level_questions(driver: str) -> list[dict]:
    """One question per maturity level (100-500) for the given driver."""
    return [
        _make_question(f"TST_{level}", driver, level)
        for level in score_frontier.LEVELS
    ]


