# Minimal pattern targets: P1 (low bar), P6 (all 500)
_P1_P6_TARGETS = {
    "1": {
        "ai_strategy": 200,
        "business_strategy": 200,
        "ai_governance": 300,
        "technology_data": 300,
        "organization_culture": 300,
    },
    "6": {
        "ai_strategy": 500,
        "business_strategy": 500,
        "ai_governance": 500,
        "technology_data": 500,
        "organization_culture": 500,
    },
}


class TestPatternReadiness:
    """Unit tests for assess_pattern_readiness()."""

    @staticmethod
    def _scores(**kwargs: int) -> dict[str, dict]:
        return {driver: {"score": score} for driver, score in kwargs.items()}

    def test_pattern_1_ready_at_exact_threshold(self) -> None:
        """P1 needs 200/200/300/300/300; all exactly at threshold → ready=True, no gaps."""
        scores = self._scores(
            ai_strategy=200,
            business_strategy=200,
            ai_governance=300,
            technology_data=300,
            organization_culture=300,
        )
        result = score_frontier.assess_pattern_readiness(scores, _P1_P6_TARGETS)
        assert result["1"]["ready"] is True
        assert result["1"]["gap_drivers"] == []
        assert result["1"]["min_gap"] == 0

    def test_pattern_6_requires_500_across(self) -> None:
        """P6 needs all 500; score of 499 anywhere → not ready; all 500 → ready."""
        not_ready_scores = self._scores(
            ai_strategy=499,
            business_strategy=500,
            ai_governance=500,
            technology_data=500,
            organization_culture=500,
        )
        result = score_frontier.assess_pattern_readiness(not_ready_scores, _P1_P6_TARGETS)
        assert result["6"]["ready"] is False
        gap_drivers = result["6"]["gap_drivers"]
        assert any(g["driver"] == "ai_strategy" for g in gap_drivers)

        ready_scores = self._scores(
            ai_strategy=500,
            business_strategy=500,
            ai_governance=500,
            technology_data=500,
            organization_culture=500,
        )
        result_ready = score_frontier.assess_pattern_readiness(ready_scores, _P1_P6_TARGETS)
        assert result_ready["6"]["ready"] is True

    def test_min_gap_is_smallest_positive(self) -> None:
        """When multiple gap_drivers exist, min_gap is the smallest gap value."""
        # P1 targets: ai_strategy=200, business_strategy=200, ai_governance=300,
        #             technology_data=300, organization_culture=300
        scores = self._scores(
            ai_strategy=100,         # gap 100 to 200
            business_strategy=200,   # OK
            ai_governance=250,       # gap 50 to 300 ← smallest
            technology_data=200,     # gap 100 to 300
            organization_culture=200, # gap 100 to 300
        )
        result = score_frontier.assess_pattern_readiness(scores, _P1_P6_TARGETS)
        assert result["1"]["ready"] is False
        assert result["1"]["min_gap"] == 50

    def test_exceeding_target_counts_as_ready(self) -> None:
        """Scores above target threshold satisfy readiness — current >= target is sufficient."""
        scores = self._scores(
            ai_strategy=400,
            business_strategy=300,
            ai_governance=500,
            technology_data=400,
            organization_culture=350,
        )
        result = score_frontier.assess_pattern_readiness(scores, _P1_P6_TARGETS)
        assert result["1"]["ready"] is True

    def test_gap_driver_fields(self) -> None:
        """Each gap_driver dict has driver, current, target, gap keys."""
        scores = self._scores(
            ai_strategy=100,
            business_strategy=200,
            ai_governance=300,
            technology_data=300,
            organization_culture=300,
        )
        result = score_frontier.assess_pattern_readiness(scores, _P1_P6_TARGETS)
        assert result["1"]["ready"] is False
        gd = result["1"]["gap_drivers"][0]
        assert gd["driver"] == "ai_strategy"
        assert gd["current"] == 100
        assert gd["target"] == 200
        assert gd["gap"] == 100


