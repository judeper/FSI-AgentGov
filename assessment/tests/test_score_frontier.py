class TestScaleBreaker:
    """Unit tests for detect_scale_breaker()."""

    @staticmethod
    def _scores(**kwargs: int) -> dict[str, dict]:
        return {driver: {"score": score} for driver, score in kwargs.items()}

    def test_detects_lowest_driver(self) -> None:
        """Lowest-scoring driver is returned as scale_breaker.driver with correct score."""
        scores = self._scores(
            ai_strategy=300,
            business_strategy=150,
            ai_governance=400,
            technology_data=350,
            organization_culture=250,
        )
        result = score_frontier.detect_scale_breaker(scores)
        assert result["driver"] == "business_strategy"
        assert result["score"] == 150
        assert result["tied_with"] == []

    def test_handles_ties(self) -> None:
        """Two drivers tied at minimum: primary is first in DRIVER_IDS; second in tied_with."""
        scores = self._scores(
            ai_strategy=300,
            business_strategy=100,
            ai_governance=400,
            technology_data=350,
            organization_culture=100,
        )
        result = score_frontier.detect_scale_breaker(scores)
        assert result["driver"] == "business_strategy"
        assert result["score"] == 100
        assert "organization_culture" in result["tied_with"]
        assert "business_strategy" not in result["tied_with"]

    def test_canonical_order_for_5way_tie(self) -> None:
        """All 5 drivers tied → first in DRIVER_IDS is primary; remaining 4 in tied_with."""
        scores = self._scores(
            ai_strategy=200,
            business_strategy=200,
            ai_governance=200,
            technology_data=200,
            organization_culture=200,
        )
        result = score_frontier.detect_scale_breaker(scores)
        assert result["driver"] == "ai_strategy"
        assert result["score"] == 200
        assert len(result["tied_with"]) == 4
        assert result["tied_with"][0] == "business_strategy"

    def test_empty_driver_scores_returns_none(self) -> None:
        """Empty dict → driver=None, score=None, tied_with=[]."""
        result = score_frontier.detect_scale_breaker({})
        assert result["driver"] is None
        assert result["score"] is None
        assert result["tied_with"] == []

    def test_rationale_always_populated(self) -> None:
        """rationale field is always a non-empty string."""
        result = score_frontier.detect_scale_breaker(self._scores(ai_strategy=300))
        assert isinstance(result["rationale"], str)
        assert len(result["rationale"]) > 0


